/**
 * Every name mentioned (course fellows, extracted people pages, dev seed) →
 * migration/review/people-candidates.md, one section per group of spellings
 * that may be one person.
 *
 *   npx tsx migration/people-candidates.ts
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

import { candidateGroups } from './lib/name-candidates'
import type { PeoplePage } from './lib/people-schema'

const here = import.meta.dirname
const root = path.join(here, '..')

const mentions: Array<{ name: string; where: string }> = []

const courses = JSON.parse(readFileSync(path.join(root, 'seed/data/archive/courses.json'), 'utf8')) as Array<{
  title: string
  cycle: string
  fellows: Array<{ name: string }>
}>
for (const c of courses)
  for (const f of c.fellows) mentions.push({ name: f.name, where: `course "${c.title}" (${c.cycle})` })

const dir = path.join(here, 'extracted/people')
for (const file of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const { data } = JSON.parse(readFileSync(path.join(dir, file), 'utf8')) as { data: PeoplePage }
  for (const p of data.people) mentions.push({ name: p.name, where: `page ${file.replace(/\.json$/, '')} (${p.group})` })
}

const seed = readFileSync(path.join(root, 'seed/collections/users.seed.ts'), 'utf8')
for (const m of seed.matchAll(/\bname: '((?:[^'\\]|\\.)*)'/g))
  mentions.push({ name: m[1].replace(/\\'/g, "'"), where: 'dev seed' })

const groups = candidateGroups(mentions)
const placesOf = (name: string): string[] => [
  ...new Set(mentions.filter((m) => m.name.trim() === name).map((m) => m.where)),
]

const out = [
  '# People: name candidates',
  '',
  `Generated by migration/people-candidates.ts. ${groups.length} groups of spellings that may be one person.`,
  '',
  ...groups.flatMap((g, i) => [
    `## ${i + 1}. ${g[0]}`,
    '',
    ...g.flatMap((name) => [`- **${name}**`, ...placesOf(name).map((w) => `  - ${w}`)]),
    '',
  ]),
]
mkdirSync(path.join(here, 'review'), { recursive: true })
writeFileSync(path.join(here, 'review/people-candidates.md'), out.join('\n'))
console.log(`${groups.length} groups`)
