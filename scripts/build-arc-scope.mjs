// Writes src/components/admin/dashboard/arc-scope.css from the Arc tokens in
// src/components/arc/foundation.css, scoped under `.arc-scope`.
//
// The admin and Arc define the same custom property names (--background,
// --accent, --border). Importing foundation.css would repaint the admin and
// replace its focus rings, so the dashboard takes only the token blocks, under
// a wrapper class. Accent presets and global focus rules are dropped.
//
// Run `node scripts/build-arc-scope.mjs` after updating Arc.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const source = readFileSync(new URL('src/components/arc/foundation.css', root), 'utf8')
const target = fileURLToPath(new URL('src/components/admin/dashboard/arc-scope.css', root))

export const topLevelRules = (css) => {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, '')
  const rules = []
  let depth = 0
  let start = 0
  let open = -1
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '{') {
      if (depth === 0) open = i
      depth++
    } else if (text[i] === '}') {
      depth--
      if (depth === 0) {
        rules.push({ prelude: text.slice(start, open).trim(), body: text.slice(open + 1, i) })
        start = i + 1
      }
    }
  }
  return rules
}

const scoped = (rule) => {
  const selector = rule.prelude
  if (selector === ':root') return `.arc-scope {${rule.body}}`
  if (selector === ":root[data-theme='dark']")
    return `[data-theme='dark'] .arc-scope {${rule.body}}`
  if (selector.startsWith('@supports')) {
    const inner = topLevelRules(rule.body).map(scoped).filter(Boolean)
    return inner.length ? `${selector} {\n${inner.join('\n')}\n}` : null
  }
  return null
}

export const buildScope = (css) =>
  [
    '/* Generated by scripts/build-arc-scope.mjs from src/components/arc/foundation.css. Do not edit. */',
    ...topLevelRules(css).map(scoped).filter(Boolean),
    '/* The admin font shows through; Arc keeps its own fonts on the site. */',
    '.arc-scope {\n  --font-display: inherit;\n  --font-body: inherit;\n}',
    '',
  ].join('\n')

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(target, buildScope(source))
  console.log(`wrote ${target}`)
}
